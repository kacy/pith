#!/usr/bin/env python3
"""Generate the tables std.markdown compiles against.

Run from the repository root:

    python3 tools/markdowngen/generate.py

This writes std/markdown/tables.pith. The data comes from python's standard
library, so nothing is downloaded:

- `html.entities.html5` is the html5 named character reference table. Only
  the names that end in a semicolon are kept, since commonmark recognizes no
  other form.
- `unicodedata` gives the general categories. CommonMark counts a character
  in a P (punctuation) or S (symbol) category as punctuation when it decides
  whether a `*` or `_` run can open or close emphasis.
- `str.casefold` gives full case folding. std.text folds one code point to one
  code point; link labels need the full mapping too (`ẞ` matches `SS`), so the
  folds that produce more than one code point are kept here.

The tables use the packing std.text.tables reads: fixed-width records of
4-character base64 fields, sorted by their first field, so a lookup is a
binary search over the string. The entity table is the exception, since its
key is a name: one line per entity, the name, a space, and one or two packed
code points. See tools/unicodegen/README.md for why tables are strings and not
list literals.
"""

import html.entities
import os
import sys
import unicodedata

# reuse unicodegen's field packing, without leaving bytecode in its directory
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "unicodegen"))

from generate import encode_field, pack  # noqa: E402

OUTPUT = os.path.join("std", "markdown", "tables.pith")

HEADER = """# generated by tools/markdowngen/generate.py -- do not edit by hand
#
# unicode {version}, and the html5 named character references that python's
# html.entities carries.
#
# regenerate with:
#     python3 tools/markdowngen/generate.py
#
# the range and fold tables are fixed-width base64 records that
# std.text.tables reads and binary-searches in place. the entity table is one
# line per entity, sorted by name, which std.markdown binary-searches the same
# way."""


def entity_records():
    lines = []
    for name, value in html.entities.html5.items():
        if not name.endswith(";"):
            continue
        bare = name[:-1]
        if not bare.isascii() or not bare.isalnum():
            raise SystemExit(f"unexpected entity name {name!r}")
        if not 1 <= len(value) <= 2:
            raise SystemExit(f"entity {name!r} expands to {len(value)} code points")
        fields = "".join(encode_field(ord(ch)) for ch in value)
        lines.append((bare, fields))
    lines.sort(key=lambda item: item[0].encode("ascii"))
    return "".join(f"{name} {fields}\\n" for name, fields in lines), len(lines)


def punctuation_ranges():
    ranges = []
    for code_point in range(0x110000):
        if unicodedata.category(chr(code_point))[0] not in "PS":
            continue
        if ranges and ranges[-1][1] == code_point - 1:
            ranges[-1][1] = code_point
        else:
            ranges.append([code_point, code_point])
    return pack([tuple(r) for r in ranges], 2), len(ranges)


def full_folds():
    records = []
    for code_point in range(0x110000):
        folded = chr(code_point).casefold()
        if len(folded) < 2:
            continue
        if len(folded) > 3:
            raise SystemExit(f"U+{code_point:04X} folds to {len(folded)} code points")
        points = [ord(ch) for ch in folded] + [0] * (3 - len(folded))
        records.append((code_point, *points))
    return pack(records, 4), len(records)


def main():
    entities, entity_count = entity_records()
    punctuation, punctuation_count = punctuation_ranges()
    folds, fold_count = full_folds()

    body = [HEADER.format(version=unicodedata.unidata_version)]
    body.append("")
    body.append("# html5 named character references that end in `;`, sorted by name.")
    body.append("# each line is the name without `&` and `;`, a space, and one or two")
    body.append("# packed code points.")
    body.append(f"# {entity_count} entries.")
    body.append(f'pub ENTITIES := "{entities}"')
    body.append("")
    body.append("# unicode punctuation and symbols (general categories P and S), as")
    body.append("# (first, last) code point ranges.")
    body.append(f"# {punctuation_count} records of 2 fields.")
    body.append(f'pub PUNCTUATION_RANGES := "{punctuation}"')
    body.append("")
    body.append("# full case foldings that produce more than one code point, as (code")
    body.append("# point, first, second, third), with 0 for an unused slot.")
    body.append(f"# {fold_count} records of 4 fields.")
    body.append(f'pub FULL_FOLDS := "{folds}"')
    body.append("")
    body.append("# how many entries ENTITIES has.")
    body.append("pub fn entity_count() -> Int:")
    body.append(f"    return {entity_count}")
    body.append("")
    body.append("# how many records PUNCTUATION_RANGES has.")
    body.append("pub fn punctuation_count() -> Int:")
    body.append(f"    return {punctuation_count}")
    body.append("")
    body.append("# how many records FULL_FOLDS has.")
    body.append("pub fn full_fold_count() -> Int:")
    body.append(f"    return {fold_count}")
    body.append("")

    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    with open(OUTPUT, "w", encoding="utf-8") as out:
        out.write("\n".join(body))
    print(f"wrote {OUTPUT}: {entity_count} entities, {punctuation_count} punctuation ranges, {fold_count} full folds")


if __name__ == "__main__":
    main()
